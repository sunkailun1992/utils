package com.kellen.config.dubbo;

/**
 * Dubbo 调用失败的重试类别，对应调用端统一重试设计的失败分类表。
 *
 * @author 孙凯伦
 */
enum DubboFailureCategory {

    /**
     * 未发出：连接还没就绪，或提供方正暂时被移出可用列表、等待目录复查。请求没到服务端，任何方法都重试到截止时间。
     */
    UNPROCESSED,

    /**
     * 无可等待的提供方：目录里一个提供方都没有，或全部可用但路由后为空（如灰度强制标签没有匹配实例）。立即失败。
     */
    NO_WAITABLE_PROVIDER,

    /**
     * 发出后暂时失败：请求可能已到服务端，因连接断开或服务端暂不可用而失败。只有声明了幂等的方法才重试。
     */
    SENT_TRANSIENT,

    /**
     * 超时。不重试。
     */
    TIMEOUT,

    /**
     * 其它：序列化、鉴权、限流、方法不存在、校验等带明确错误码的失败，以及判定不了的失败。不重试。
     */
    OTHER
}
